// Copies the storefront (../site) into ./public — the folder the server (and the Docker image) serves.
// Prototype-only files (dev server, QA screenshots, test tooling) are left behind.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '..', '..', 'site'), out = path.resolve(here, '..', 'public');
const SKIP = new Set(['server.js', 'start.bat', 'README.md', 'qa', 'tools', 'node_modules', 'server.log']);

fs.rmSync(out, { recursive: true, force: true });
let files = 0, bytes = 0;
(function copy(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    if (SKIP.has(e.name) || e.name.endsWith('.log') || e.name === 'config.js') continue;      // config.js is generated by the server, never a file
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (e.isDirectory()) copy(a, b); else { fs.copyFileSync(a, b); files++; bytes += fs.statSync(a).size; }
  }
})(src, out);

// Compress text files once, here, instead of on every request: the server (and any CDN in front of it) serves the .br / .gz twin as-is.
let packed = 0, saved = 0;
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { walk(p); continue; }
    if (!/\.(html|js|css|svg|json|txt|xml|webmanifest)$/i.test(e.name)) continue;
    const raw = fs.readFileSync(p); if (raw.length < 1024) continue;
    const br = zlib.brotliCompressSync(raw, { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11, [zlib.constants.BROTLI_PARAM_SIZE_HINT]: raw.length } });
    fs.writeFileSync(p + '.br', br); fs.writeFileSync(p + '.gz', zlib.gzipSync(raw, { level: 9 })); packed++; saved += raw.length - br.length;
  }
})(out);
console.log(`public/ ready: ${files} files, ${(bytes / 1048576).toFixed(1)} MB; ${packed} text files pre-compressed (brotli saves ${(saved / 1048576).toFixed(1)} MB)`);
